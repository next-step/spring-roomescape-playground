CREATE TABLE time
(
    id BIGINT NOT NULL AUTO_INCREMENT,
    time VARCHAR(5) NOT NULL UNIQUE,
    PRIMARY KEY (id)
);

CREATE TABLE reservation
(
    id BIGINT NOT NULL AUTO_INCREMENT,
    name VARCHAR(5) NOT NULL,
    date VARCHAR(5) NOT NULL,
    time_id BIGINT,
    PRIMARY KEY (id),
    FOREIGN KEY (time_id) REFERENCES time(id)
);
